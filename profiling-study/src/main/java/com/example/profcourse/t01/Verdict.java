/** Готовый класс, менять не нужно. Куда смотреть дальше. */
public enum Verdict {
    /** Время ответа в пределах нормы — расследовать нечего. */
    NO_DEGRADATION,
    /** CPU машины занят не нашим процессом. */
    OTHER_PROCESS,
    /** Приложение заметную долю времени стоит в паузах GC. */
    GC_PRESSURE,
    /** Внешняя система отвечает медленнее обычного. */
    DEPENDENCY_SLOW,
    /** Все соединения пула заняты, потоки ждут в очереди. */
    POOL_SATURATED,
    /** Процесс сам съедает CPU — нужен CPU-профиль. */
    CPU_IN_CODE,
    /** CPU свободен, причина не видна в метриках — нужны дампы потоков. */
    WAITING_UNKNOWN
}
